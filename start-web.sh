#!/usr/bin/bash
# start-web.sh —— **现在只是一层 shim**（2026-10-08 起启动器是 python）。
#
# 为什么不直接删掉这个名字：它是用户肌肉记忆里的入口（`./start-web.sh`），
# 也是文档与脚本里凡提到「启动器」就写的名字。留着 shim 让**旧调用方式继续有效**，
# 同时把实现收敛到唯一一份 —— 这正是本仓库反复在做的事：
# **同一件事只能有一个位置**。
#
# 为什么用 exec：不留下多余的 bash 进程。前台模式下 Ctrl+C 的进程组关系不变，
# 信号不被中间层吃掉（中间层转发信号是最容易出错的环节，这里直接绕开它）。
#
# ⚠️ 实现全在 start-web.py（python + 标准库）。**不要在这里加逻辑** ——
#    这里只有一行 exec。要加逻辑，加到 start-web.py 里去。
exec /usr/bin/python3 "$(dirname "$(readlink -f "$0")")/start-web.py" "$@"
